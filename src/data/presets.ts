export interface PresetDish {
  title: string;
  type: Food["type"];
  attributes?: DietaryRestriction[];
}

export interface PresetMarketing {
  slug: string;
  headline: string;
  subheadline: string;
  metaTitle: string;
  metaDescription: string;
  keywords: string[];
}

export type PresetCategory =
  | "holiday"
  | "seasonal"
  | "dietary"
  | "sports"
  | "cuisine"
  | "life"
  | "cozy";

export interface PotluckPreset {
  id: string;
  name: string;
  emoji: string;
  date?: string;
  categories: PresetCategory[];
  featured?: boolean;
  tagline?: string;
  dishes: PresetDish[];
  marketing?: PresetMarketing;
}

function dish(
  title: string,
  type: Food["type"],
  attributes?: DietaryRestriction[],
): PresetDish {
  return attributes ? { title, type, attributes } : { title, type };
}

